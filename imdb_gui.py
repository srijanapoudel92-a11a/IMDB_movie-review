import gradio as gr
import joblib

saved_model = joblib.load("sentiment_analysis_model.pkl")

tfidf = saved_model["vectorizer"]
model = saved_model["model"]


def predict_sentiment(review):
    if not review or not review.strip():
        return "Please enter a movie review"

    review_tfidf = tfidf.transform([review])
    prediction = model.predict(review_tfidf)[0]

    return "Predicted Sentiment: " + prediction.upper()

demo = gr.Interface(
    fn=predict_sentiment,

    inputs=gr.Textbox(
        lines=5,
        placeholder="Enter your movie review",
        label="Movie Review"
    ),

    outputs=gr.Textbox(label="Sentiment Prediction"),
    title="Movie Review Sentiment Analysis",
    description="Enter a movie review to predict whether it is positive or negative."
)

demo.launch()